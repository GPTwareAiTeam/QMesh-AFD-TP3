#!/usr/bin/env bash
# Reproducible DSpark retention overlay package.
#
# Extracts the two exact files from the pinned image (CPU-only, no GPU access),
# applies the pinned patcher, verifies every hash, and writes:
#
#   src/vllm/...      byte-identical image sources (provenance)
#   overlay/vllm/...  patched files mounted by scripts/launch_engine_graphs.sh
#   manifest.txt      image identity + all hashes
#
# Usage:
#   bash p7/dspark_retention/package.sh          # regenerate + verify
#   bash p7/dspark_retention/package.sh --check  # verify only, write nothing
#   bash p7/dspark_retention/package.sh --help   # this text, no docker access
#
# Regeneration needs the pinned patcher. Set PATCHER to it directly, or set
# VLLM_SRC to a vllm-moet checkout and it is taken from
# $VLLM_SRC/tools/dsv41_sm120/patch_vllm_dspark_retention.py. There is no
# built-in checkout path. IMAGE overrides the pinned image tag.
#
# The launcher mounts overlay/ only when SPEC_TOKENS>0 and independently checks
# the same image id and hashes, so a stale or locally edited copy cannot boot.
set -euo pipefail

PKG=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
VLLM_SRC=${VLLM_SRC:-}
PATCHER=${PATCHER:-${VLLM_SRC:+$VLLM_SRC/tools/dsv41_sm120/patch_vllm_dspark_retention.py}}
IMAGE=${IMAGE:-vllm-moet:dsv41-213d5fa}
EXPECTED_IMAGE_ID=sha256:9a21de6e8ba7ade4df4590841401edd09c406638ad21bb22d6f170c297d0f404
EXPECTED_COMMIT=49cb2bbf71cfd36ee5aa33d1e184b1cddff55294
VLLM_LIB=/usr/local/lib/python3.12/dist-packages

REL_FILES=(
  vllm/v1/core/kv_cache_planning.py
  vllm/v1/attention/backends/mla/sparse_swa.py
)
EXPECTED_SRC_SHA=(
  dd03a0eb2a75eebdc6b912f0cffa50bb6d3e06f0810c4d964bc9de30dc2a3360
  66b246e8d2d1ea5fbd192da1c9250c2e47bc9824c774cb5e22bf093277bc1fe4
)
EXPECTED_OVERLAY_SHA=(
  103daabfd0df9e9a8e52938a781e119c3da6cafce08308190d5672a0631db06a
  363268c27d32d652bca0c3b17098574cdaf029255e81dd17c8cc465e723b16f2
)

CHECK_ONLY=0
case "${1:-}" in
  "") ;;
  --check) CHECK_ONLY=1 ;;
  -h|--help)
    sed -n '2,22p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
    exit 0 ;;
  *) echo "usage: $0 [--check|--help]" >&2; exit 2 ;;
esac

die() { echo "package: $*" >&2; exit 1; }
sha() { local out; out=$(sha256sum "$1"); echo "${out%% *}"; }

image_id=$(docker image inspect --format '{{.Id}}' "$IMAGE" 2>/dev/null) ||
  die "image not found: $IMAGE"
[[ "$image_id" == "$EXPECTED_IMAGE_ID" ]] ||
  die "image id $image_id != $EXPECTED_IMAGE_ID"
commit=$(docker image inspect --format '{{index .Config.Labels "ai.vllm.build.commit"}}' "$IMAGE" 2>/dev/null) ||
  commit=""
[[ "$commit" == "$EXPECTED_COMMIT" ]] ||
  die "image build commit '$commit' != '$EXPECTED_COMMIT'"
if [[ "$CHECK_ONLY" == 0 ]]; then
  [[ -n "$PATCHER" && -f "$PATCHER" ]] ||
    die "patcher not found; set PATCHER or VLLM_SRC (a vllm-moet checkout)"
fi

manifest() {
  {
    echo "# DSpark retention overlay manifest (generated by package.sh; do not edit)"
    echo "image: $IMAGE"
    echo "image_id: $EXPECTED_IMAGE_ID"
    echo "build_commit: $EXPECTED_COMMIT"
    echo "patcher: tools/dsv41_sm120/patch_vllm_dspark_retention.py (location varies; pinned by patcher_sha256)"
    echo "patcher_sha256: $1"
    echo "semantics: extra_retained_tokens=max(existing, num_speculative_tokens+1) only when use_dspark(); ComputeDSparkNoncausalSWAIndicesKernel masks null block 0 to -1; non-spec path unchanged"
    echo "source_sha256:"
    for i in "${!REL_FILES[@]}"; do
      echo "  ${REL_FILES[$i]}: ${EXPECTED_SRC_SHA[$i]}"
    done
    echo "overlay_sha256:"
    for i in "${!REL_FILES[@]}"; do
      echo "  ${REL_FILES[$i]}: ${EXPECTED_OVERLAY_SHA[$i]}"
    done
  } >"$PKG/manifest.txt"
}

# Apache-2.0 section 4(b) notice, applied to patcher output so regenerating
# the package keeps the same bytes and hashes.
add_license_notices() {
  python3 - "$PKG/overlay/${REL_FILES[0]}" "$PKG/overlay/${REL_FILES[1]}" <<'PY'
import sys
from pathlib import Path

NOTICES = {
    "kv_cache_planning.py": (
        "\n"
        "# Modified by QMesh (2026) for the DSV4.1 AFD-TP3 experiment.\n"
        "# DSpark retention: when use_dspark() is active, retain at least\n"
        "# num_speculative_tokens + 1 tokens below a sliding-window boundary; the\n"
        "# non-DSpark path is unchanged.\n"
        "# Provenance and license: third_party/vllm/NOTICE\n"
    ),
    "sparse_swa.py": (
        "\n"
        "# Modified by QMesh (2026) for the DSV4.1 AFD-TP3 experiment.\n"
        "# DSpark retention: map context positions in the null SWA block (block 0) to\n"
        "# slot -1 so they cannot alias real KV; other paths are unchanged.\n"
        "# Provenance and license: third_party/vllm/NOTICE\n"
    ),
}

marker = "Modified by QMesh (2026) for the DSV4.1 AFD-TP3 experiment."
for arg in sys.argv[1:]:
    path = Path(arg)
    text = path.read_text()
    if marker in text:
        continue
    lines = text.splitlines(keepends=True)
    at = 0
    while at < len(lines) and lines[at].startswith("# SPDX-"):
        at += 1
    lines.insert(at, NOTICES[path.name])
    path.write_text("".join(lines))
PY
}

verify_overlay() {
  for i in "${!REL_FILES[@]}"; do
    local rel=${REL_FILES[$i]} got
    [[ -f "$PKG/src/$rel" ]] || die "missing src/$rel; run package.sh"
    got=$(sha "$PKG/src/$rel")
    [[ "$got" == "${EXPECTED_SRC_SHA[$i]}" ]] ||
      die "src/$rel hash $got != ${EXPECTED_SRC_SHA[$i]}"
    [[ -f "$PKG/overlay/$rel" ]] || die "missing overlay/$rel; run package.sh"
    got=$(sha "$PKG/overlay/$rel")
    [[ "$got" == "${EXPECTED_OVERLAY_SHA[$i]}" ]] ||
      die "overlay/$rel hash $got != ${EXPECTED_OVERLAY_SHA[$i]}"
  done
  python3 - "$PKG/overlay/${REL_FILES[0]}" "$PKG/overlay/${REL_FILES[1]}" <<'PY'
import sys
for path in sys.argv[1:]:
    with open(path) as f:
        compile(f.read(), path, "exec")
PY
}

if [[ "$CHECK_ONLY" == 1 ]]; then
  [[ -f "$PKG/manifest.txt" ]] || die "manifest.txt missing; run package.sh"
  verify_overlay
  echo "package: OK (image $EXPECTED_IMAGE_ID, overlay hashes verified)"
  exit 0
fi

patcher_sha=$(sha "$PATCHER")
tmp=$(mktemp -d "$PKG/.extract.XXXXXX")
trap 'rm -rf "$tmp"' EXIT

# Extract from the exact image. --runtime runc and --network none keep this a
# plain CPU file read; no GPU device is requested or touched.
rm -rf "$PKG/src" "$PKG/overlay"
for i in "${!REL_FILES[@]}"; do
  rel=${REL_FILES[$i]}
  mkdir -p "$tmp/$(dirname "$rel")" "$PKG/src/$(dirname "$rel")"
  docker run --rm --runtime runc --network none --entrypoint cat \
    "$IMAGE" "$VLLM_LIB/$rel" >"$tmp/$rel" ||
    die "failed to extract $rel from $IMAGE"
  got=$(sha "$tmp/$rel")
  [[ "$got" == "${EXPECTED_SRC_SHA[$i]}" ]] ||
    die "extracted $rel hash $got != ${EXPECTED_SRC_SHA[$i]}"
  cp "$tmp/$rel" "$PKG/src/$rel"
done

mkdir -p "$PKG/overlay"
python3 "$PATCHER" --vllm-dir "$PKG/src/vllm" --overlay-dir "$PKG/overlay"
add_license_notices

for i in "${!REL_FILES[@]}"; do
  rel=${REL_FILES[$i]}
  got=$(sha "$PKG/overlay/$rel")
  [[ "$got" == "${EXPECTED_OVERLAY_SHA[$i]}" ]] ||
    die "patched $rel hash $got != ${EXPECTED_OVERLAY_SHA[$i]} (patcher output drifted)"
done
verify_overlay
manifest "$patcher_sha"
echo "package: wrote $PKG/{src,overlay,manifest.txt}"
echo "package: overlay kv_cache_planning.py ${EXPECTED_OVERLAY_SHA[0]}"
