#!/usr/bin/env bash
# Reproducible native-context-memory overlay package.
#
# Extracts two vLLM files from the pinned image (CPU-only, no GPU access),
# applies each pinned patcher, verifies every hash, and writes:
#
#   src/...      byte-identical image sources (provenance)
#   overlay/...  the patched files mounted read-only by
#                scripts/launch_engine_graphs.sh when NATIVE_CTX_MEM=1
#   manifest.txt image identity + all hashes
#
# The indexer patch replaces `get_max_prefill_buffer_size`'s 8.7x
# flashmla_sparse envelope with the exact per-chunk bound `factor *
# max_model_len`. It does not change chunk arithmetic, scores, top-k, KV
# layout, or max_model_len; check_bounds.py proves the chunker's N invariant
# and byte-exactness of the rest of the file on CPU.
#
# The mxfp8_utils patch makes `dequant_mxfp8_to_bf16` reuse its fresh float32
# weight copy instead of allocating a second weight-sized temporary.
# check_mxfp8_dequant.py proves bit-identical CPU torch results, including
# NaN, infinities and negative zero.
#
# Usage:
#   bash p7/native_context_memory/package.sh          # regenerate + verify
#   bash p7/native_context_memory/package.sh --check  # verify only, no writes
#   bash p7/native_context_memory/package.sh --help   # this text, no docker
#
# IMAGE overrides the pinned image tag for extraction; the id and build commit
# must still match. The launcher independently checks the same image id and
# hashes, so a stale or locally edited copy cannot boot.
set -euo pipefail

PKG=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
IMAGE=${IMAGE:-vllm-moet:dsv41-213d5fa}
EXPECTED_IMAGE_ID=sha256:9a21de6e8ba7ade4df4590841401edd09c406638ad21bb22d6f170c297d0f404
EXPECTED_COMMIT=49cb2bbf71cfd36ee5aa33d1e184b1cddff55294
VLLM_LIB=/usr/local/lib/python3.12/dist-packages

REL_INDEXER=vllm/v1/attention/backends/mla/indexer.py
EXPECTED_INDEXER_SRC_SHA=3150214befd174998b02cd2fc254a9b03966b20f4da2372af0c5fc5a956d61fe
EXPECTED_INDEXER_OVERLAY_SHA=6c4185759db3172a6cd1dc625b8e7cca083d49ccbd9ea07991f14cfda8305ed6
PATCHER_INDEXER="$PKG/patch_indexer_prefill_bound.py"
EXPECTED_INDEXER_PATCHER_SHA=3c1282b3521be820909ad990ec939d56afb1687eb2d76dac3db91b4adfc6783c

REL_MXFP8=vllm/model_executor/layers/quantization/utils/mxfp8_utils.py
EXPECTED_MXFP8_SRC_SHA=03a16184c905b3a5f0f4aa52736cefeb0528d97fa3d79a85da08d10b68b86c09
EXPECTED_MXFP8_OVERLAY_SHA=d70568eeb878bfc0b2f3ce1b49ce4f76a5520711d2cf54218adbd68481c744e9
PATCHER_MXFP8="$PKG/patch_mxfp8_dequant.py"
EXPECTED_MXFP8_PATCHER_SHA=8caf4085b7322daf6ab4545ac7197008af48ff2a2861346c98df9a93f164e8e5

CHECK_ONLY=0
case "${1:-}" in
  "") ;;
  --check) CHECK_ONLY=1 ;;
  -h|--help)
    sed -n '2,30p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
    exit 0 ;;
  *) echo "usage: $0 [--check|--help]" >&2; exit 2 ;;
esac

die() { echo "package: $*" >&2; exit 1; }
sha() { local out; out=$(sha256sum "$1"); echo "${out%% *}"; }

image_id=$(docker image inspect --format '{{.Id}}' "$IMAGE" 2>/dev/null) ||
  die "image not found: $IMAGE"
[[ "$image_id" == "$EXPECTED_IMAGE_ID" ]] ||
  die "image id $image_id != $EXPECTED_IMAGE_ID"
commit=$(docker image inspect --format '{{index .Config.Labels "ai.vllm.build.commit"}}' "$IMAGE" 2>/dev/null) ||
  commit=""
[[ "$commit" == "$EXPECTED_COMMIT" ]] ||
  die "image build commit '$commit' != '$EXPECTED_COMMIT'"

manifest() {
  local indexer_patcher_sha=$1 indexer_checker_sha=$2
  local mxfp8_patcher_sha=$3 mxfp8_checker_sha=$4
  {
    echo "# Native 1M context-memory overlay manifest (generated by package.sh; do not edit)"
    echo "image: $IMAGE"
    echo "image_id: $EXPECTED_IMAGE_ID"
    echo "build_commit: $EXPECTED_COMMIT"
    echo "patcher: p7/native_context_memory/patch_indexer_prefill_bound.py"
    echo "patcher_sha256: $indexer_patcher_sha"
    echo "mxfp8_patcher: p7/native_context_memory/patch_mxfp8_dequant.py"
    echo "mxfp8_patcher_sha256: $mxfp8_patcher_sha"
    echo "checker: p7/native_context_memory/check_bounds.py"
    echo "checker_sha256: $indexer_checker_sha"
    echo "mxfp8_checker: p7/native_context_memory/check_mxfp8_dequant.py"
    echo "mxfp8_checker_sha256: $mxfp8_checker_sha"
    echo "semantics: get_max_prefill_buffer_size returns max_model_len*factor (exact per-chunk bound) instead of max_model_len*(576*2//132)*factor; chunker, scores, top-k, KV layout and max_model_len unchanged"
    echo "mxfp8_dequant_semantics: dequant_mxfp8_to_bf16 reuses the fresh float32 x_float copy with an in-place broadcast multiply instead of allocating a second weight-sized float32 temporary; float32 multiply and bf16 cast unchanged"
    echo "savings_at_1M_factor2_mxfp4: indexer K gather 1.0625 GiB -> 0.1328 GiB (-0.9297 GiB); block tables unchanged by this file (MAX_NUM_BATCHED_TOKENS=2048 halves 256 MiB -> 128 MiB)"
    echo "mxfp8_dequant_savings: wo_a [8192,4096] FP8 dequant no longer allocates the second 128 MiB float32 temporary; only the 64 MiB bf16 result remains"
    echo "source_sha256:"
    echo "  $REL_INDEXER: $EXPECTED_INDEXER_SRC_SHA"
    echo "  $REL_MXFP8: $EXPECTED_MXFP8_SRC_SHA"
    echo "overlay_sha256:"
    echo "  $REL_INDEXER: $EXPECTED_INDEXER_OVERLAY_SHA"
    echo "  $REL_MXFP8: $EXPECTED_MXFP8_OVERLAY_SHA"
  } >"$PKG/manifest.txt"
}

verify_file() {
  local rel=$1 src_sha=$2 overlay_sha=$3 got
  [[ -f "$PKG/src/$rel" ]] || die "missing src/$rel; run package.sh"
  got=$(sha "$PKG/src/$rel")
  [[ "$got" == "$src_sha" ]] ||
    die "src/$rel hash $got != $src_sha"
  [[ -f "$PKG/overlay/$rel" ]] || die "missing overlay/$rel; run package.sh"
  got=$(sha "$PKG/overlay/$rel")
  [[ "$got" == "$overlay_sha" ]] ||
    die "overlay/$rel hash $got != $overlay_sha"
  python3 - "$PKG/overlay/$rel" <<'PY'
import sys
path = sys.argv[1]
with open(path) as f:
    compile(f.read(), path, "exec")
PY
}

verify_overlay() {
  verify_file "$REL_INDEXER" "$EXPECTED_INDEXER_SRC_SHA" \
    "$EXPECTED_INDEXER_OVERLAY_SHA"
  verify_file "$REL_MXFP8" "$EXPECTED_MXFP8_SRC_SHA" \
    "$EXPECTED_MXFP8_OVERLAY_SHA"
  # CPU-only semantic proof: byte-exact patch application, chunker N invariant
  # at 1M/factor 2/ratios 1,2,8, and the 1M footprint table.
  python3 "$PKG/check_bounds.py" >/dev/null ||
    die "check_bounds.py failed; overlay semantics are not proven"
  # CPU-only torch proof in the pinned image (runc, no network, no GPU).
  docker run --rm --runtime runc --network none -e CUDA_VISIBLE_DEVICES= \
    -v "$PKG:/pkg:ro" --entrypoint python3 "$IMAGE" \
    /pkg/check_mxfp8_dequant.py --src /pkg/src --overlay /pkg/overlay \
    >/dev/null ||
    die "check_mxfp8_dequant.py failed; mxfp8 dequant bits are not proven"
}

if [[ "$CHECK_ONLY" == 1 ]]; then
  [[ -f "$PKG/manifest.txt" ]] || die "manifest.txt missing; run package.sh"
  for _spec in \
    "$PATCHER_INDEXER:$EXPECTED_INDEXER_PATCHER_SHA" \
    "$PATCHER_MXFP8:$EXPECTED_MXFP8_PATCHER_SHA"; do
    _patcher=${_spec%%:*}
    _expected=${_spec##*:}
    got=$(sha "$_patcher")
    [[ "$got" == "$_expected" ]] ||
      die "patcher $(basename "$_patcher") hash $got != $_expected"
  done
  verify_overlay
  echo "package: OK (image $EXPECTED_IMAGE_ID, both overlays + patchers verified)"
  exit 0
fi

for _spec in \
  "$PATCHER_INDEXER:$EXPECTED_INDEXER_PATCHER_SHA" \
  "$PATCHER_MXFP8:$EXPECTED_MXFP8_PATCHER_SHA"; do
  _patcher=${_spec%%:*}
  _expected=${_spec##*:}
  [[ -f "$_patcher" ]] || die "patcher missing: $_patcher"
  got=$(sha "$_patcher")
  [[ "$got" == "$_expected" ]] ||
    die "patcher $(basename "$_patcher") hash $got != $_expected (update pins deliberately)"
done
indexer_patcher_sha=$(sha "$PATCHER_INDEXER")
mxfp8_patcher_sha=$(sha "$PATCHER_MXFP8")
indexer_checker_sha=$(sha "$PKG/check_bounds.py")
mxfp8_checker_sha=$(sha "$PKG/check_mxfp8_dequant.py")

tmp=$(mktemp -d "$PKG/.extract.XXXXXX")
trap 'rm -rf "$tmp"' EXIT

# Extract from the exact image. --runtime runc and --network none keep this a
# plain CPU file read; no GPU device is requested or touched.
extract_one() {
  local rel=$1 expected=$2 got
  mkdir -p "$tmp/$(dirname "$rel")" "$PKG/src/$(dirname "$rel")"
  docker run --rm --runtime runc --network none --entrypoint cat \
    "$IMAGE" "$VLLM_LIB/$rel" >"$tmp/$rel" ||
    die "failed to extract $rel from $IMAGE"
  got=$(sha "$tmp/$rel")
  [[ "$got" == "$expected" ]] ||
    die "extracted $rel hash $got != $expected"
  cp "$tmp/$rel" "$PKG/src/$rel"
}

rm -rf "$PKG/src" "$PKG/overlay"
extract_one "$REL_INDEXER" "$EXPECTED_INDEXER_SRC_SHA"
extract_one "$REL_MXFP8" "$EXPECTED_MXFP8_SRC_SHA"

mkdir -p "$PKG/overlay"
python3 "$PATCHER_INDEXER" --src "$PKG/src" --out "$PKG/overlay"
python3 "$PATCHER_MXFP8" --src "$PKG/src" --out "$PKG/overlay"

verify_overlay
manifest "$indexer_patcher_sha" "$indexer_checker_sha" \
  "$mxfp8_patcher_sha" "$mxfp8_checker_sha"
echo "package: wrote $PKG/{src,overlay,manifest.txt}"
echo "package: overlay indexer.py $EXPECTED_INDEXER_OVERLAY_SHA"
echo "package: overlay mxfp8_utils.py $EXPECTED_MXFP8_OVERLAY_SHA"
